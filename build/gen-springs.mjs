/* Generates assets/css/src/springs.css from assets/js/motion-tokens.js so CSS
   transitions and the JS engine share one set of spring physics.
   Usage: node build/gen-springs.mjs   (also runs as part of `npm run build`) */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { springs, springStep, springSettleTime } from '../assets/js/motion-tokens.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'assets/css/src/springs.css');

const fmt = (n) => String(Math.round(n * 10000) / 10000);
let css = '/* GENERATED by build/gen-springs.mjs from assets/js/motion-tokens.js — do not edit. */\n:root {\n';

for (const [name, cfg] of Object.entries(springs)) {
  const settle = springSettleTime(cfg);                 // seconds
  const points = Math.min(110, Math.max(24, Math.round(settle * 80)));
  const samples = [];
  for (let i = 0; i <= points; i++) samples.push(springStep(cfg, (settle * i) / points));
  samples[samples.length - 1] = 1;                      // land exactly
  css += `  --spring-${name}: linear(${samples.map(fmt).join(', ')});\n`;
  css += `  --spring-${name}-duration: ${Math.round(settle * 1000)}ms;\n`;
}
css += '}\n';

writeFileSync(out, css);
console.log(`springs.css written (${Object.keys(springs).length} curves)`);
